#!/usr/bin/env python3
"""Keep the native GLSL algorithm synchronized with the original artwork."""
import json
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1]
html = (root / 'artwork/index.html').read_text()
shader = re.search(r'const fragmentShaderSource = `(.+?)`', html, re.S)[1]
shader = re.sub(r'#ifdef GL_FRAGMENT_PRECISION_HIGH.*?#endif', '', shader, flags=re.S)
shader = '#version 150\nout vec4 outputColor;\n' + shader.replace('gl_FragColor', 'outputColor')
# WebGL's default premultiplied canvas over the black page keeps RGB unchanged.
# The native window is opaque: only output alpha changes, not RGB or the algorithm.
shader = shader.replace('mainImage(outputColor, gl_FragCoord.xy);', 'mainImage(outputColor, gl_FragCoord.xy);\n    outputColor.a = 1.0;')
result = '/* Generated by tools/generate_shader.py. Do not hand edit. */\nstatic const char *fragment_source =\n' + '\n'.join(json.dumps(line + '\n') for line in shader.splitlines()) + ';\n'
target = root / 'native/shader.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != result:
        raise SystemExit('Stale native shader: run tools/generate_shader.py')
else:
    target.write_text(result)
